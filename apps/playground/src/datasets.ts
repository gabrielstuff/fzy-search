import { buildCorpus } from '../../../bench/corpus.js';

export type Row = { id: number | string; name: string; meta?: string };

export type Dataset = {
  id: string;
  label: string;
  /** Where the rows come from, shown under the results. */
  source: string;
  load: () => Promise<Row[]>;
  /** Queries worth trying, as a human would type them. */
  examples: { filter: string[]; typo: string[] };
};

// The same generator the benchmark uses: long, accented, multi-word French labels.
const formations = (size: number): Dataset => ({
  id: `formations-${size / 1000}k`,
  label: `${size.toLocaleString('en')} formations (generated)`,
  source: 'Formations: generated by bench/corpus.js, the benchmark corpus',
  load: async () => buildCorpus(size),
  examples: {
    filter: [
      'sicences donnes',
      'oenologie',
      'info cloud devops',
      'managment comercial',
      'informatiquecloud',
      'cybersecu paris',
    ],
    // The typo preset matches a word against short names (minCoverage 0.8): a long label never qualifies.
    typo: [],
  },
});

type Commune = { nom: string; code: string; codeDepartement: string; population?: number };

export const DATASETS: Dataset[] = [
  formations(20000),
  formations(5000),
  formations(50000),
  formations(100000),
  {
    id: 'communes',
    label: '34 969 French communes (real)',
    source: 'Communes: geo.api.gouv.fr, Licence Ouverte',
    load: async () => {
      const response = await fetch('https://geo.api.gouv.fr/communes?fields=nom,codeDepartement,population');
      if (!response.ok) throw new Error(`geo.api.gouv.fr answered ${response.status}`);
      const communes = (await response.json()) as Commune[];
      return communes.map((c) => ({
        id: c.code,
        name: c.nom,
        meta: `${c.codeDepartement}${c.population ? ` · ${c.population.toLocaleString('fr')} hab.` : ''}`,
      }));
    },
    examples: {
      filter: ['st etienne', 'chalon sur saone', 'aix provence', 'clermon ferand', 'montpelier', 'lyon'],
      typo: ['renned', 'avginon', 'besancn', 'bordeax', 'commerce'],
    },
  },
];
