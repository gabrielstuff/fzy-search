// Renders a sweep (bench/sweep-<label>.json, written by bench/sweep.js) as results-<label>.md: the
// tables only. The method and the reading of the numbers live in results.md, which does not change
// from one machine to the next.
//
//   node bench/report.js bench/sweep-mbp.json      # rerender without rerunning
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FZY = 'fzy-search';
const kb = (n) => `${(n / 1024).toFixed(1)} kB`;

// A markdown table. `cols` are [header, value fn, best] where best is 'min', 'max' or undefined; the
// best value of a column is bold, and so is the fzy-search row's name. Rows come sorted by the first
// column that has a direction.
function table(rows, cols) {
  const sortBy = cols.find((c) => c[2]);
  const sorted = sortBy ? rows.slice().sort((a, b) => (sortBy[2] === 'min' ? 1 : -1) * (sortBy[1](a) - sortBy[1](b))) : rows;
  const best = cols.map(([, get, dir]) => (dir ? Math[dir](...rows.map(get).filter((v) => typeof v === 'number')) : undefined));
  const lines = [`| library | ${cols.map((c) => c[0]).join(' | ')} |`, `|---|${cols.map(() => '---').join('|')}|`];
  for (const r of sorted) {
    const name = r.name === FZY ? `**${r.name}**` : r.name;
    const cells = cols.map(([, get, , fmt = (v) => v], i) => {
      const v = get(r);
      if (typeof v !== 'number') return v ?? '—';
      const s = fmt(v);
      return v === best[i] ? `**${s}**` : s;
    });
    lines.push(`| ${name} | ${cells.join(' | ')} |`);
  }
  return lines.join('\n');
}

const f0 = (v) => v.toFixed(0);
const f1 = (v) => v.toFixed(1);
const f2 = (v) => v.toFixed(2);
const f3 = (v) => v.toFixed(3);

export function render(s) {
  const { machine: m, versions: v, contenders } = s;
  const corpora = Object.keys(s.corpora);
  const L = [];
  const p = (...x) => L.push(...x, '');
  const by = (c, name) => s.corpora[c].results.find((r) => r.name === name);
  const noise = (c, name) => s.corpora[c].noise.find((r) => r.name === name);
  const mem = (c, name) => s.corpora[c].mem.find((r) => r.name === name);
  const rows = contenders.map((name) => ({ name }));
  const per = (get, dir, fmt) => corpora.map((c) => [c, (r) => get(c, r.name), dir, fmt]);

  p(`# Benchmark results — ${m.label}`);
  p(
    `Generated by \`node bench/sweep.js --label ${m.label}\` at commit \`${m.commit}\` on ${m.date}. Do not edit: rerun it. ` +
      `What each section measures, and how to read it, is in [results.md](results.md).`,
  );
  p('| | |', '|---|---|', `| machine | ${m.cpu}, ${m.cores} cores, ${m.memoryGb} GB |`, `| os | ${m.os} |`, `| node | ${m.node} |`, `| fzy-search | ${v[FZY]} (${m.lib}) |`, `| contenders | ${Object.entries(v).filter(([n]) => n !== FZY).map(([n, ver]) => `${n} ${ver}`).join(', ')} |`);
  p('| corpus | rows | labeled queries |', '|---|---|---|', ...corpora.map((c) => `| \`${c}\` | ${s.corpora[c].rows.toLocaleString('en-US')} | ${s.corpora[c].queries} |`));

  p('## 1. Bundle cost — esbuild, minified');
  p('Each library bundled alone with only the entry points a search box needs; for fzy-search that is `createIndex` + `search`.');
  p(table(s.size, [['min', (r) => r.min, undefined, kb], ['gzip', (r) => r.gzip, 'min', kb], ['brotli', (r) => r.br, undefined, kb]]));

  p('## 2. Relevance — top-1 %');
  p('How often the one correct row is ranked first.');
  p(table(rows, per((c, n) => by(c, n)?.top1, 'max', f1)));
  p('MRR@10:');
  p(table(rows, per((c, n) => by(c, n)?.mrr, 'max', f3)));
  p('Recall@10 %:');
  p(table(rows, per((c, n) => by(c, n)?.recall, 'max', f1)));

  p('## 3. False positives — %, queries with no answer');
  p('Two real corpus words that never share a row. Any result is a row that matched half the query. Lower is better.');
  p(table(rows, per((c, n) => noise(c, n)?.falsePositiveRate, 'min', f1)));

  p('## 4. Speed — per-query latency, ms');
  p('p50:');
  p(table(rows, per((c, n) => by(c, n)?.p50, 'min', f2)));
  p('p95:');
  p(table(rows, per((c, n) => by(c, n)?.p95, 'min', f2)));
  p('max:');
  p(table(rows, per((c, n) => by(c, n)?.max, 'min', f2)));

  // match-sorter has no index: its build is a no-op and its heap delta is noise around zero.
  const indexed = (v, floor) => (typeof v === 'number' && v < floor ? '—' : v);
  p('## 5. Index build, ms');
  p('Median of two builds. match-sorter has no index.');
  p(table(rows, per((c, n) => indexed(by(c, n)?.buildMs, 1), 'min', f0)));
  p('## 6. Retained heap of one index, MB');
  p('The index alone, on top of the corpus, each measured in its own process (`bench/mem.js`).');
  p(table(rows, per((c, n) => indexed(mem(c, n)?.mb, 0.1), 'min', f1)));

  p('## 7. Typo robustness — top-1 % per query shape');
  for (const c of corpora) {
    const cats = Object.keys(s.corpora[c].results[0].byCat);
    p(`\`${c}\`:`);
    p(table(rows, cats.map((cat) => [cat, (r) => by(c, r.name)?.byCat[cat], 'max', f0])));
  }

  if (s.scaling) {
    p('## 8. Scaling — fzy-search, synthetic vocabularies');
    p('Latency tracks the number of distinct words, not the number of rows.');
    p('| rows | distinct words | build | p50 | p95 |', '|---|---|---|---|---|', ...s.scaling.map((r) => `| ${r.rows.toLocaleString('en-US')} | ${r.vocab.toLocaleString('en-US')} | ${f0(r.buildMs)} ms | ${f2(r.p50)} ms | ${f2(r.p95)} ms |`));
  }
  return L.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const file = process.argv[2];
  if (!file) throw new Error('usage: node bench/report.js bench/sweep-<label>.json');
  const sweep = JSON.parse(readFileSync(file, 'utf8'));
  const out = new URL(`../results-${sweep.machine.label}.md`, import.meta.url);
  writeFileSync(out, render(sweep));
  console.log(`wrote results-${sweep.machine.label}.md`);
}
